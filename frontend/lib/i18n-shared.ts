/**
 * 纯翻译函数，可在服务端与客户端共享调用
 */
export function translate(locale: Locale, key: string, defaultText?: string): string {
  const dict = DICTIONARY[locale];
  if (dict && dict[key]) {
    return dict[key];
  }
  return defaultText || key;
}
